// Style previews: the style's specimen page (engine/style/specimen.ts), drawn by the engine with the style's own roles:
// a title, a table in a panel with dimmed rows and an emphasized answer, a labeled diagram with pointers, and an
// archival photo beside a generated picture with words over them. The picker shows a still and a short loop of it, so
// every style is judged on the same page, and the style writer shows Spark the same still.
// Usage: node --experimental-strip-types app/preview.ts [<style> ...]   (all top-level and custom styles by default)
import { existsSync, mkdirSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { bundle } from "@remotion/bundler";
import { renderMedia, renderStill, selectComposition } from "@remotion/renderer";
import { compile } from "../engine/core/compile.ts";
import { themeFrom } from "../engine/render/theme.ts";
import { type Pictures, specimen } from "../engine/style/specimen.ts";

const fps = 30;
const STAGE = 24; // frames between the page's four parts arriving
export const PREVIEW_FRAMES = STAGE * 4 + 54;
export const STILL_FRAME = PREVIEW_FRAMES - 4; // everything is on screen and settled
export const PREVIEWS = resolve("styles/previews");

// Two pictures that stay with the previews: a CC0 archival photo (1900 Wright glider reproduction, Ken Hyde and the
// Wright Experience Team, Wikimedia Commons) and one generated by the pipeline, so a style shows how it joins them.
const SPECIMEN = join(PREVIEWS, "specimen");
let pictures: Pictures | undefined;
function pics(): Pictures {
  if (pictures) return pictures;
  const load = (f: string) => `data:image/jpeg;base64,${readFileSync(join(SPECIMEN, f)).toString("base64")}`;
  return (pictures = { photo: load("photo.jpg"), photoW: 900, photoH: 600, made: load("made.jpg"), madeW: 360, madeH: 640 });
}

let served: Promise<string> | undefined;
const serveUrl = () => (served ??= bundle({ entryPoint: resolve("engine/render/preview.tsx") }));
const chrome = { gl: "angle" as const };
const browserExecutable = process.env.BETTERVID_CHROME || null;

// Styles the picker offers: the files in styles/, then the ones people made in styles/custom/.
export function allStyles(): string[] {
  const json = (folder: string) => (existsSync(folder) ? readdirSync(folder).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort() : []);
  return [...json("styles"), ...json("styles/custom").map((n) => `custom/${n}`)];
}

async function composition(style: string) {
  const theme = themeFrom(style); // refuses a style whose design layer is incomplete or unreadable
  const file = JSON.parse(readFileSync(resolve("styles", `${style}.json`), "utf8"));
  const scene = compile(specimen(theme, "after", pics(), file.vignette ?? 0, STAGE), { fps, width: 1080, height: 1920, frames: PREVIEW_FRAMES, theme });
  const inputProps = { scene, theme };
  const url = await serveUrl();
  return { url, inputProps, comp: await selectComposition({ serveUrl: url, id: "Scene", inputProps, chromiumOptions: chrome, browserExecutable }) };
}

// One still of the finished page, small enough for the page and for a model to look at.
export async function previewStill(style: string, output: string, frame = STILL_FRAME, scale = 0.5): Promise<string> {
  const { url, inputProps, comp } = await composition(style);
  mkdirSync(dirname(output), { recursive: true });
  await renderStill({ serveUrl: url, composition: comp, inputProps, frame, imageFormat: "jpeg", jpegQuality: 86, scale, output, chromiumOptions: chrome, browserExecutable });
  return output;
}

// The picker's assets for a style: <name>.jpg and a silent <name>.webm loop, under styles/previews/.
export async function preview(style: string): Promise<{ still: string; loop: string }> {
  const still = join(PREVIEWS, `${style}.jpg`);
  const loop = join(PREVIEWS, `${style}.webm`);
  await previewStill(style, still, STILL_FRAME, 0.4);
  const { url, inputProps, comp } = await composition(style);
  await renderMedia({ serveUrl: url, composition: comp, inputProps, codec: "vp9", crf: 36, scale: 0.4, concurrency: 2, muted: true, outputLocation: loop, chromiumOptions: chrome, browserExecutable });
  return { still, loop };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const list = process.argv.slice(2);
  for (const style of list.length ? list : allStyles()) {
    const t0 = Date.now();
    await preview(style);
    console.log(`${style}: ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
}
